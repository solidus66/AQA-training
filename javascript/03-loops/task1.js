// Задание 1. Test Counter
// Создай цикл, который выводит номера тестов от 1 до 10.
// Требования:
// - Использовать цикл for.
// - Начать счётчик с 1.
// - Завершить цикл на 10.
// - Для каждого теста вывести сообщение в формате Running test #N.

for (let testNumber = 1; testNumber <= 10; testNumber++) {
  console.log(`Running test #${testNumber}`);
}
